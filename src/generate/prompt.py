"""Промпт для LLM. Правила: только по контексту, ссылки [n], точная фраза отказа."""
from .. import config
from ..retrieve.index import index_text
from ..schema import Hit

SYSTEM = (
    "Ты помощник сотрудников группы компаний. Отвечай ТОЛЬКО по приведённому контексту.\n"
    "Правила:\n"
    "1. Ответ короткий: одно-два предложения, по-русски, с конкретными значениями "
    "(числа, единицы измерения, сроки, названия) так, как они написаны в контексте.\n"
    "2. После каждого факта ставь номер фрагмента в квадратных скобках, например [1].\n"
    "3. Если вопрос про место в документе, назови документ и страницу/пункт из шапки фрагмента.\n"
    f"4. Если в контексте нет ответа, ответь ровно: «{config.NO_ANSWER}». "
    "Не выдумывай и не используй знания вне контекста."
)


def build_messages(question: str, hits: list[Hit]) -> list[dict]:
    context = "\n\n".join(
        f"[{i}] {h.chunk.location}\n{index_text(h.chunk)}" for i, h in enumerate(hits, 1)
    )
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content": f"Контекст:\n{context}\n\nВопрос: {question}\nОтвет:"},
    ]
