"""Правила роутера: ключевые слова компаний.

Слово ищется с НАЧАЛА слова: «чат» найдёт «чаты», «чатов», но не «начать».
Пополняйте списки по реальным документам и публичным вопросам на хакатоне.
"""
import re

from .. import config

KEYWORDS: dict[str, list[str]] = {
    "tehnoprom": [
        "станк", "станок", "оборудован", "руководств", "эксплуатац", "техпаспорт", "паспорт",
        "чертеж", "чертёж", "класс точност", "техобслуж", "обслуживан", "автопилот", "схем",
        "тп-", "миэлта", "технопром",
    ],
    "logistics": [
        "доставк", "тариф", "договор", "акт сверк", "акты сверк", "груз", "перевоз",
        "склад", "штраф", "трансгруз", "смартагро", "логистик", "отгрузк",
    ],
    "retail": [
        "возврат", "вернуть", "верну", "товар", "остатк", "заказ", "покупател",
        "чат", "поддержк", "артикул", "полетн", "полётн", "контроллер",
        "агродинамик", "розниц",
    ],
}

_PATTERNS = {
    company: [re.compile(r"(?<!\w)" + re.escape(kw.strip().replace("ё", "е")), re.I)
              for kw in dict.fromkeys(kws)]
    for company, kws in KEYWORDS.items()
}


def rule_scores(question: str) -> dict[str, float]:
    q = question.lower().replace("ё", "е")
    return {c: float(sum(bool(p.search(q)) for p in pats))
            for c, pats in _PATTERNS.items() if c in config.COMPANY_TITLES}
